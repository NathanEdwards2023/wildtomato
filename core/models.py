from django.conf import settings
from django.db import models


class Employee(models.Model):
    id = models.AutoField(primary_key=True)
    first_name = models.CharField(max_length=100)
    last_name = models.CharField(max_length=100)
    hourly_rate = models.DecimalField(max_digits=10, decimal_places=2)
    role = models.CharField(max_length=7)
    active = models.BooleanField(default=True)
    user = models.OneToOneField(settings.AUTH_USER_MODEL, null=True, blank=True,
                                on_delete=models.SET_NULL)

    class Meta:
        managed = False
        db_table = "employee"

    def __str__(self):
        return f"{self.first_name} {self.last_name}"


class DiningTable(models.Model):
    table_id = models.AutoField(primary_key=True)
    name = models.CharField(max_length=50, unique=True)
    seats = models.IntegerField()

    class Meta:
        managed = False
        db_table = "dining_table"
        ordering = ["name"]

    def __str__(self):
        return self.name


class TableOrder(models.Model):
    """Read mapping of the shared SQL orders table; SQL owns its schema."""
    class Status(models.TextChoices):
        OPEN = "open", "Open"
        CLOSED = "closed", "Closed"

    number = models.AutoField(primary_key=True)
    table = models.ForeignKey(DiningTable, on_delete=models.PROTECT, related_name="orders")
    employee = models.ForeignKey(Employee, on_delete=models.PROTECT)
    status = models.CharField(max_length=6, choices=Status, default=Status.OPEN)
    order_time = models.DateTimeField()
    credit = models.BooleanField(default=False)
    card_fee = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    gratuity = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    note = models.CharField(max_length=255, null=True, blank=True)

    # open_table_id is generated by MySQL and is never written by this mapping.
    class Meta:
        managed = False
        db_table = "orders"

    def __str__(self):
        return f"Order #{self.pk} - {self.table}"
